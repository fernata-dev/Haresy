"""Bundle the app's ES modules into classic scripts that run anywhere.

Why: browsers refuse module scripts (and module workers) in sandboxed frames with an opaque
origin (e.g. an embedded preview) and on file:// pages, so a module-only page is blank there.
The modules in src/bawwab/web/{app,engine,samples} stay the source of truth (the Node parity tests
import them); this writes
  src/bawwab/web/bundle.js               the whole app, one classic script
  src/bawwab/web/engine/worker-bundle.js the checking engine for the background worker
Only the import/export forms used in this project are supported; anything else raises.
usage: python tools/web/bundle.py [--check]
"""
from __future__ import annotations

import posixpath
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
WEB = ROOT / "src" / "bawwab" / "web"

IMPORT_NAMED = re.compile(r'^import\s*\{([^}]*)\}\s*from\s*"([^"]+)";[ \t]*$', re.M | re.S)
IMPORT_DEFAULT = re.compile(r'^import\s+(\w+)\s+from\s*"([^"]+)";[ \t]*$', re.M)
DYNAMIC = re.compile(r'\bimport\("([^"]+)"\)')
WORKER = 'new Worker(new URL("../engine/worker.js", import.meta.url), {type: "module"})'


def _resolve(frm: str, spec: str) -> str:
    return posixpath.normpath(posixpath.join(posixpath.dirname(frm), spec))


def transform(mid: str, src: str) -> tuple[str, list[str]]:
    deps: list[str] = []

    def named(m):
        dep = _resolve(mid, m.group(2))
        deps.append(dep)
        names = [n.strip() for n in m.group(1).replace("\n", " ").split(",") if n.strip()]
        parts = [f"{a.strip()}: {b.strip()}" if " as " in n else n for n in names for a, b in [n.split(" as ") if " as " in n else (n, n)]]
        return f"const {{{', '.join(parts)}}} = __req({dep!r});"

    def default(m):
        dep = _resolve(mid, m.group(2))
        deps.append(dep)
        return f"const {m.group(1)} = __req({dep!r}).default;"

    src = IMPORT_NAMED.sub(named, src)
    src = IMPORT_DEFAULT.sub(default, src)
    src = src.replace(WORKER, "new Worker(self.BAWWAB_WORKER_URL)")
    for d in DYNAMIC.findall(src):                       # collect BEFORE rewriting them
        deps.append(_resolve(mid, d))
    src = DYNAMIC.sub(lambda m: f"__req({_resolve(mid, m.group(1))!r})", src)
    exports: list[str] = []
    src = re.sub(r"^export\s+(async\s+function|function|const|let)\s+(\w+)",
                 lambda m: (exports.append(m.group(2)), f"{m.group(1)} {m.group(2)}")[1], src, flags=re.M)
    src = re.sub(r"^export\s+default\s+(\w+);", lambda m: (exports.append(f"default: {m.group(1)}"), "")[1], src, flags=re.M)
    src = re.sub(r"^export\s*\{([^}]*)\};", lambda m: (exports.extend(n.strip() for n in m.group(1).split(",")), "")[1], src, flags=re.M)
    if re.search(r"^\s*(import|export)\b", src, re.M) or "import.meta" in src:
        raise SystemExit(f"bundle.py: unsupported module syntax left in {mid}")
    body = f'__def({mid!r}, function () {{\n"use strict";\n{src}\nreturn {{{", ".join(exports)}}};\n}});\n'
    return body, deps


def bundle(entry: str, header: str) -> str:
    order: list[str] = []
    bodies: dict[str, str] = {}

    def visit(mid: str) -> None:
        if mid in bodies:
            return
        bodies[mid] = ""                      # mark (no cycles in this project)
        body, deps = transform(mid, (WEB / mid).read_text(encoding="utf-8"))
        for d in deps:
            visit(d)
        bodies[mid] = body
        order.append(mid)

    visit(entry)
    missing = {r for b in bodies.values() for r in re.findall(r"__req\('([^']+)'\)", b)} - set(bodies)
    if missing:
        raise SystemExit(f"bundle.py: modules required but not bundled: {sorted(missing)}")
    loader = ("(function () {\n\"use strict\";\nconst __defs = {}, __cache = {};\n"
              "function __def(id, fn) { __defs[id] = fn; }\n"
              "function __req(id) { if (!(id in __cache)) { if (!__defs[id]) throw new Error('missing module ' + id); "
              "__cache[id] = __defs[id](); } return __cache[id]; }\n")
    return (f"// GENERATED by tools/web/bundle.py from the ES modules ({header}). Do not edit.\n" + loader
            + "".join(bodies[m] for m in order) + f"__req({entry!r});\n}})();\n")


def outputs() -> dict[Path, str]:
    app = bundle("app/main.js", "app/*, engine/*, samples/*")
    app = app.replace('"use strict";\nconst __defs', '"use strict";\nself.BAWWAB_WORKER_URL = "engine/worker-bundle.js";\nconst __defs', 1)
    return {WEB / "bundle.js": app, WEB / "engine" / "worker-bundle.js": bundle("engine/worker.js", "engine/*")}


def main(argv: list[str]) -> int:
    outs = outputs()
    if "--check" in argv:
        stale = [str(p.relative_to(ROOT)) for p, t in outs.items() if not p.exists() or p.read_text(encoding="utf-8") != t]
        print("bundles up to date" if not stale else "bundles STALE: " + ", ".join(stale))
        return 1 if stale else 0
    for p, t in outs.items():
        p.write_text(t, encoding="utf-8")
        print(f"wrote {p.relative_to(ROOT)} ({len(t)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
