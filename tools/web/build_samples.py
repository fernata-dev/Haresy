"""Bundle the example documents for the app's "Try an example" buttons into one JS module.

Some static hosts refuse .docx / .eml files, so the samples ship as base64 inside
src/bawwab/web/samples/samples.js. They are the synthetic documents from
tools/parity/make_doc_fixtures.py (mock attacker address only).
usage: python tools/web/build_samples.py
"""
from __future__ import annotations

import base64
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "tools" / "parity"))
import make_doc_fixtures as M  # noqa: E402

NAMES = ("hidden.docx", "mail.eml", "page.html", "smuggle.txt")


def main() -> None:
    out = ROOT / "src" / "bawwab" / "web" / "samples"
    out.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory() as d:
        M.build(Path(d))
        data = {n: base64.b64encode((Path(d) / n).read_bytes()).decode("ascii") for n in NAMES}
    for old in out.iterdir():
        old.unlink()
    (out / "samples.js").write_text(
        "// GENERATED by tools/web/build_samples.py: synthetic example documents (base64).\n"
        f"const SAMPLES = {json.dumps(data, indent=1, sort_keys=True)};\nexport default SAMPLES;\n", encoding="utf-8")
    print("wrote samples.js")


if __name__ == "__main__":
    main()
